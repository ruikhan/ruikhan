const callClaudeAPI = async (prompt) => {
  try {
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'claude-sonnet-4-20250514',
        max_tokens: 3000,
        messages: [{ role: 'user', content: prompt }]
      })
    });

    if (!response.ok) {
      throw new Error(`API error: ${response.status}`);
    }

    const data = await response.json();
    
    if (!data.content || !Array.isArray(data.content) || !data.content[0] || !data.content[0].text) {
      throw new Error('Invalid API response structure');
    }
    
    return data.content[0].text;
  } catch (error) {
    console.error('API call failed:', error);
    throw error;
  }
};

const parseStructuredResponse = (text) => {
  // Simple parser - in production, use more sophisticated parsing
  try {
    // Try to extract JSON if present
    const jsonMatch = text.match(/```json\n([\s\S]*?)\n```/);
    if (jsonMatch) {
      return JSON.parse(jsonMatch[1]);
    }
    
    // Otherwise return as structured text object
    return {
      raw: text,
      sections: text.split('\n\n').filter(s => s.trim()),
      timestamp: Date.now()
    };
  } catch (error) {
    return { raw: text, error: 'Parse failed' };
  }
};

const calculateWeightedScore = (scores, weights) => {
  // Extract scores from parsed response and calculate weighted average
  // This is a simplified version
  let total = 0;
  let weightSum = 0;
  
  Object.entries(weights).forEach(([key, weight]) => {
    // Try to extract score for this criterion
    const scoreMatch = scores.raw?.match(new RegExp(`${key}.*?(\\d+)/100`, 'i'));
    if (scoreMatch) {
      total += parseInt(scoreMatch[1]) * weight;
      weightSum += weight;
    }
  });
  
  return weightSum > 0 ? Math.round(total / weightSum) : 75; // Default fallback
};

const logProcess = (message) => {
  workflowEngine.processingLog.push({
    time: Date.now(),
    message
  });
};

