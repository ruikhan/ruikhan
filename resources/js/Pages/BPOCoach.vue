  const variations = currentWorkflow.value.variations;
  const variationKeys = ['A', 'B', 'C'];
  const key = variationKeys[variationIndex];
  
  // Extract variation text from raw response
  const variationMatch = variations.raw.match(
    new RegExp(`VARIATION ${key}:.*?\\[Full rewritten answer\\]\\s*([\\s\\S]*?)(?=\\*\\*VARIATION|$)`, 'i')
  );
  
  if (variationMatch) {
    userAnswers[currentStageData.value.id] = variationMatch[1].trim();
  }
};

